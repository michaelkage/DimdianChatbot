-- Optional PostgreSQL schema for the staff inbox.
-- Import only when staff_inbox.enabled is deliberately enabled.
-- One business per database remains the supported tenant boundary.
-- After importing this file, apply database/postgresql/migrations/006_tenant_owned_staff_storage.sql.
-- That migration adds tenant ownership and composite same-tenant foreign keys;
-- staff repository SQL is still installation-wide, so shared-database mode remains unsafe.

CREATE TABLE staff_identities (
    id UUID PRIMARY KEY,
    auth_provider VARCHAR(40) NOT NULL,
    external_subject VARCHAR(191) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(254),
    role VARCHAR(16) NOT NULL DEFAULT 'agent' CHECK (role IN ('owner', 'admin', 'agent')),
    status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (auth_provider, external_subject)
);
CREATE INDEX idx_staff_status_role ON staff_identities(status, role);

CREATE TABLE staff_conversation_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    staff_identity_id UUID NOT NULL REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    assigned_by_staff_id UUID NOT NULL REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITHOUT TIME ZONE,
    active_conversation_id UUID UNIQUE
);
CREATE INDEX idx_staff_assignment_agent ON staff_conversation_assignments(staff_identity_id, ended_at, assigned_at);
CREATE INDEX idx_staff_assignment_history ON staff_conversation_assignments(conversation_id, assigned_at);

CREATE TABLE staff_internal_notes (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id UUID PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    author_staff_id UUID NOT NULL REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    body TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_staff_notes_conversation ON staff_internal_notes(conversation_id, created_at, id);

CREATE TABLE staff_message_authors (
    message_id UUID PRIMARY KEY REFERENCES messages(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    staff_identity_id UUID NOT NULL REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_staff_message_author ON staff_message_authors(staff_identity_id, message_id);

CREATE TABLE staff_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_staff_id UUID NOT NULL REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    conversation_id UUID REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    event_type VARCHAR(64) NOT NULL,
    target_staff_id UUID REFERENCES staff_identities(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    metadata_json TEXT,
    request_id VARCHAR(64),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_staff_audit_conversation ON staff_audit_events(conversation_id, id);
CREATE INDEX idx_staff_audit_actor ON staff_audit_events(actor_staff_id, id);
CREATE INDEX idx_staff_audit_type_created ON staff_audit_events(event_type, created_at);

CREATE TABLE staff_auth_nonces (
    nonce_sha256 CHAR(64) COLLATE "C" PRIMARY KEY,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_staff_auth_nonce_expiry ON staff_auth_nonces(expires_at);
