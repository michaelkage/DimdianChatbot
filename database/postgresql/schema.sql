CREATE TABLE guests (
    id UUID PRIMARY KEY,
    display_name VARCHAR(100),
    phone VARCHAR(32),
    phone_normalized VARCHAR(32),
    whatsapp_opt_in_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_guests_phone ON guests(phone);
CREATE INDEX idx_guests_phone_normalized ON guests(phone_normalized);

CREATE TABLE conversations (
    id UUID PRIMARY KEY,
    guest_id UUID NOT NULL REFERENCES guests(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    status VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    last_message_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_conversations_guest_created ON conversations(guest_id, created_at);
CREATE INDEX idx_conversations_status_updated ON conversations(status, updated_at);

CREATE TABLE guest_sessions (
    id UUID PRIMARY KEY,
    guest_id UUID NOT NULL REFERENCES guests(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    token_hash CHAR(64) COLLATE "C" NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITHOUT TIME ZONE,
    revoked_at TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX idx_guest_sessions_guest ON guest_sessions(guest_id, created_at);
CREATE INDEX idx_guest_sessions_expiry ON guest_sessions(expires_at, revoked_at);

CREATE TABLE messages (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id UUID PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    client_message_id UUID,
    sender_type VARCHAR(16) NOT NULL CHECK (sender_type IN ('visitor', 'business', 'system')),
    body TEXT NOT NULL,
    provider_message_id VARCHAR(191) UNIQUE,
    delivery_status VARCHAR(16) NOT NULL DEFAULT 'received'
        CHECK (delivery_status IN ('queued', 'sent', 'delivered', 'read', 'failed', 'received', 'web_only')),
    sent_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (conversation_id, client_message_id)
);
CREATE INDEX idx_messages_conversation_order ON messages(conversation_id, sequence_id);

CREATE TABLE webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_event_id VARCHAR(191) NOT NULL UNIQUE,
    event_type VARCHAR(100) NOT NULL,
    payload_sha256 CHAR(64) COLLATE "C" NOT NULL,
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    processed_at TIMESTAMP WITHOUT TIME ZONE,
    processing_status VARCHAR(16) NOT NULL DEFAULT 'received'
        CHECK (processing_status IN ('received', 'processed', 'ignored', 'failed'))
);
CREATE INDEX idx_webhook_events_status_received ON webhook_events(processing_status, received_at);

CREATE TABLE rate_limits (
    bucket_key CHAR(64) COLLATE "C" PRIMARY KEY,
    window_started_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0)
);
CREATE INDEX idx_rate_limits_window ON rate_limits(window_started_at);

CREATE TABLE message_outbox (
    id UUID PRIMARY KEY,
    message_id UUID NOT NULL UNIQUE REFERENCES messages(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    recipient VARCHAR(32) NOT NULL,
    payload_text TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'sent', 'failed')),
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    locked_at TIMESTAMP WITHOUT TIME ZONE,
    lock_token UUID,
    provider_message_id VARCHAR(191),
    last_error VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_message_outbox_due ON message_outbox(status, available_at, created_at);
CREATE INDEX idx_message_outbox_lock ON message_outbox(status, locked_at);

CREATE TABLE message_status_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_message_id VARCHAR(191) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('sent', 'delivered', 'read', 'failed')),
    event_timestamp BIGINT NOT NULL DEFAULT 0 CHECK (event_timestamp >= 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    UNIQUE (provider_message_id, status, event_timestamp)
);
CREATE INDEX idx_message_status_provider ON message_status_events(provider_message_id, event_timestamp);

CREATE TABLE guest_consent_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id UUID NOT NULL REFERENCES guests(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    channel VARCHAR(24) NOT NULL,
    action VARCHAR(16) NOT NULL CHECK (action IN ('opt_in', 'opt_out')),
    source VARCHAR(40) NOT NULL,
    policy_version VARCHAR(32) NOT NULL DEFAULT '2026-11',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_consent_guest_created ON guest_consent_events(guest_id, created_at);
CREATE INDEX idx_consent_channel_action ON guest_consent_events(channel, action, created_at);

CREATE TABLE whatsapp_identity_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_normalized VARCHAR(32) NOT NULL,
    guest_id UUID NOT NULL REFERENCES guests(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    conversation_id UUID NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    active_phone VARCHAR(32) GENERATED ALWAYS AS (CASE WHEN is_active = 1 THEN phone_normalized ELSE NULL END) STORED,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deactivated_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (active_phone)
);
CREATE INDEX idx_whatsapp_link_conversation ON whatsapp_identity_links(conversation_id, is_active);

CREATE TABLE webhook_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload_sha256 CHAR(64) COLLATE "C" NOT NULL UNIQUE,
    payload_ciphertext TEXT NOT NULL,
    payload_nonce TEXT NOT NULL,
    payload_tag TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'processed', 'failed')),
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    locked_at TIMESTAMP WITHOUT TIME ZONE,
    lock_token UUID,
    last_error VARCHAR(500),
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    processed_at TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX idx_webhook_inbox_due ON webhook_inbox(status, available_at, received_at);
CREATE INDEX idx_webhook_inbox_lock ON webhook_inbox(status, locked_at);

CREATE TABLE meta_signup_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_sha256 CHAR(64) COLLATE "C" NOT NULL UNIQUE,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    used_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_meta_signup_expiry ON meta_signup_states(expires_at, used_at);

CREATE TABLE meta_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waba_id VARCHAR(80) NOT NULL,
    phone_number_id VARCHAR(80) NOT NULL UNIQUE,
    access_token_ciphertext TEXT NOT NULL,
    access_token_nonce TEXT NOT NULL,
    access_token_tag TEXT NOT NULL,
    token_expires_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked', 'expired')),
    connected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX idx_meta_connection_status ON meta_connections(status, updated_at);
